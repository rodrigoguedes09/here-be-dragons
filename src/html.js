// The interactive atlas: one self-contained HTML file (map + data + viewer).
import { realmTitle } from './names.js';
import { readFileSync } from 'node:fs';
import { chronicle, quests, realmBusFactor } from './chronicle.js';
import { labelFor } from './layout.js';

const asset = (name) => readFileSync(new URL(`./viewer/${name}`, import.meta.url), 'utf8');
const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

/** Data the viewer needs, kept compact. */
export function viewerData(realm, geo) {
  const r3 = (x) => Math.round(x * 1000) / 1000;
  return {
    name: realm.name,
    generatedAt: realm.generatedAt,
    head: realm.head,
    stats: realm.stats,
    width: geo.width,
    height: geo.height,
    files: realm.files.map((f, i) => {
      const c = geo.cities[i];
      return {
        p: f.path,
        n: labelFor(f.path),
        k: f.kind,
        l: f.lang,
        loc: f.loc,
        rev: f.revisions,
        au: f.authorCount,
        o: f.owner,
        os: r3(f.ownerShare),
        age: f.ageDays,
        hs: r3(f.hotspot),
        t: f.tested ? 1 : 0,
        ai: r3(f.aiShare),
        ru: f.ruin ? 1 : 0,
        d: f.dragon,
        pr: f.province,
        td: f.todos,
        dp: f.maxDepth,
        x: Math.round(c.x * 10) / 10,
        y: Math.round(c.y * 10) / 10,
        c: c.class,
      };
    }),
    provinces: realm.provinces.map((p) => ({
      name: (p.path || '(root)').replace(' (heartland)', ''),
      heartland: p.loose,
      files: p.files.length,
      loc: p.loc,
      owner: p.owner,
      ownerShare: r3(p.ownerShare),
      busFactor: p.busFactor,
      tested: r3(p.tested),
      aiShare: r3(p.aiShare),
      ruinShare: r3(p.ruinShare),
      todos: p.todos,
      x: Math.round(geo.provGeo[realm.provinces.indexOf(p)].x),
      y: Math.round(geo.provGeo[realm.provinces.indexOf(p)].y),
    })),
    dragons: realm.dragons,
    routes: realm.routes.map((r) => ({ a: r.a, b: r.b, shared: r.shared, degree: r3(r.degree) })),
    houses: geo.houses.map((h) => ({ name: h.name, color: h.color, loc: h.loc })),
    authors: realm.authors.slice(0, 40).map((a) => ({
      name: a.name,
      commits: a.commits,
      ownedLoc: a.ownedLoc,
      last: a.last,
      active: a.active,
    })),
    chronicle: chronicle(realm),
    quests: quests(realm),
    busFactor: realmBusFactor(realm),
  };
}

